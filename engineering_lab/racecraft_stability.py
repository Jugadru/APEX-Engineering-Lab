"""Bounded independent replay of scripted observations; no sporting motion."""
import json
import random
from itertools import combinations
from . import registry as reg, racecraft_core as core, racecraft_integration as integration
from . import racecraft_collision as collision, racecraft_personality as personality

def scenarios(seed,ticks):
    rng=random.Random(seed)
    for label in ("changing_threat","wrap_pack","seeded_pack"):
        snapshots=[]
        for t in range(ticks):
            if label=="changing_threat":
                source=integration.scripted(t,blocked=t%7 in (2,3))
                rows=source.payload()["cars"]
                for r in rows: r["progress_mm"]+=5000*t
            else:
                # External monotonic progress stream; not generated by candidate.
                # Constant speeds with scripted lane variation, including overlaps.
                rows=[core.row(i,(4990000 if label=="wrap_pack" else 100000)+i*7000+t*(6000+100*i),
                               (-1)**(i+t//4)*2500 if label=="wrap_pack" else rng.choice([-3000,0,3000]),
                               30000+500*i) for i in range(1,25)]
            snapshots.append(core.Snapshot.from_rows(t,5000000,5000,rows))
        yield label,snapshots

def replay(snapshots,reverse=False,checkpoint=False,verify=False):
    memories=None; digests=[]; invalid=switches=0; modes={}; decisions=0
    for t,s in enumerate(snapshots):
        if reverse: s=core.Snapshot.from_rows(s.tick,s.length_mm,s.half_width_mm,s.payload()["cars"][::-1])
        profiles,contexts=integration.inputs(s)
        contexts={i:personality.context(wet=(t%5)*200,wear=(i%4)*100,pressure=(t%3)*200) for i in contexts}
        if reverse:
            profiles=dict(reversed(list(profiles.items()))); contexts=dict(reversed(list(contexts.items())))
        if checkpoint and t==len(snapshots)//2:
            # Explicit integer-key restoration in diagnostic memory; not save-game support.
            memories={int(k):v for k,v in json.loads(reg.canonical(memories)).items()}
        old=reg.digest(memories) if memories is not None else None
        result=integration.plan(s,profiles,contexts,memories)
        invalid+=old!=(reg.digest(memories) if memories is not None else None)
        invalid+=bool(result["feasibility"]["new_contacts"])
        decisions+=len(result["decisions"])
        for d in result["decisions"]:
            modes[d["mode"]]=modes.get(d["mode"],0)+1
            if memories is not None:
                i=d["id"]; a=memories[i]["attack"]; b=result["memory"][i]["attack"]
                if a["target"] is not None and b["target"] is not None:
                    switches+=a["target"]!=b["target"] or a["aim_mm"]!=b["aim_mm"]
        if verify:
            ends={r["id"]:collision.endpoint(r["progress_mm"],r["lateral_mm"]) for r in result["feasibility"]["endpoints"]}
            initial={tuple(p) for p in result["feasibility"]["initial_contacts"]}
            for i,j in combinations(sorted(ends),2):
                contact=collision.oracle(s,i,j,ends[i],ends[j])
                invalid+=bool(contact["contact"]) and (i,j) not in initial
                invalid+=(i,j) in initial and not contact["initial_contact"]
        digests.append(reg.digest(result)); memories=result["memory"]
    return {"digest":reg.digest(digests),"invalid":invalid,"switches":switches,"decisions":decisions,"modes":modes}

def evaluate(config):
    rows=[]; invalid=mismatch=switches=decisions=0
    for label,snapshots in scenarios(config["seed"],config["ticks"]):
        a=replay(snapshots,verify=True)
        b=replay(snapshots,reverse=True)
        c=replay(snapshots,checkpoint=True)
        invalid+=a["invalid"]+b["invalid"]+c["invalid"]
        switches+=a["switches"]+b["switches"]+c["switches"]
        mismatch+=a["digest"]!=b["digest"] or a["digest"]!=c["digest"]
        decisions+=a["decisions"]+b["decisions"]+c["decisions"]
        rows.append(dict(scenario=label,**a,reordered_sha256=b["digest"],checkpoint_sha256=c["digest"]))
    return {"metrics":{"invalid_results":invalid,"lock_switches":switches,"replay_mismatches":mismatch},
            "observations":{"scenarios":len(rows),"observed_ticks":len(rows)*config["ticks"],"decisions_including_replays":decisions,"rows":rows,
                            "limitations":"External scripted observations, same-process deterministic replay and diagnostic memory roundtrip, not game save/replay, closed-loop driving or real race."}}

def spec(c):
    return dict(hypothesis="Repeated scripted 24-car observations preserve commitment, deterministic order and diagnostic memory continuity, with no new swept contacts.",
        sources=["REF-105","IDEA-029","IDEA-030","IDEA-033","IDEA-034","IDEA-040"],config={"seed":20261127,"ticks":20},
        criteria={"invalid_results":c("eq",0),"lock_switches":c("eq",0),"replay_mismatches":c("eq",0)},evaluate=evaluate)
